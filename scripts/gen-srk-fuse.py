#!/usr/bin/env python3
"""Write the SRK hash fuse words as C, for include/pb/srk_fuse.h.

The input is srktool's fuse file (e.g. SRK_1_2_3_4_fuse.bin): the words to
fuse, little endian, in fuse order.
"""

import pathlib
import struct
import sys


def main() -> int:
    """Print srk_fuse.c for the fuse file in argv[1]."""
    data = pathlib.Path(sys.argv[1]).read_bytes()

    if not data or len(data) % 4:
        sys.stderr.write(f"{sys.argv[1]}: not a whole number of 32 bit words\n")
        return 1

    words = struct.unpack(f"<{len(data) // 4}I", data)
    print("/* Generated by scripts/gen-srk-fuse.py from", sys.argv[1], "*/")
    print("#include <pb/srk_fuse.h>\n")
    print("const uint32_t srk_fuse[] = {")
    print("".join(f"    0x{w:08x},\n" for w in words), end="")
    print("};\n")
    print(f"const size_t srk_fuse_words = {len(words)};")
    return 0


if __name__ == "__main__":
    sys.exit(main())
