/* The key of a curve, and its length */
static inline const uint8_t *test_key(dsa_t kind, size_t *length)
{
    switch (kind) {
    case DSA_EC_SECP384r1:
        *length = sizeof(test_key_p384);
        return test_key_p384;
    case DSA_EC_SECP521r1:
        *length = sizeof(test_key_p521);
        return test_key_p521;
    case DSA_EC_SECP256r1:
    default:
        *length = sizeof(test_key_p256);
        return test_key_p256;
    }
}

