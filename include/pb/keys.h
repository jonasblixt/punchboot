#ifndef INCLUDE_PB_KEYS_H
#define INCLUDE_PB_KEYS_H

#include <pb/crypto.h>
#include <stdint.h>

/** A key pb verifies with: the board's VERIFY_KEY<n> (board.md 7) */
struct pb_key {
    key_id_t id; /*!< Its id, which images, tokens and SLC_* name */
    dsa_t kind; /*!< Its curve, DSA_EC_* */
    uint8_t slot; /*!< Its revoke slot, n of VERIFY_KEY<n> */
    uint16_t size; /*!< Size of 'data' in bytes */
    const uint8_t *data; /*!< The public key, a SubjectPublicKeyInfo in DER */
};

/** The board's keys in slot order, generated by scripts/gen-keystore.py */
extern const struct pb_key pb_keys[];
/** The number of keys in pb_keys, 1 to 16 */
extern const unsigned int pb_no_of_keys;

#endif // INCLUDE_PB_KEYS_H
